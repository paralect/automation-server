import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
const ROOT = resolve(dirname(import.meta.path), "..");
export const SOURCE_DIR = join(ROOT, "github-actions");
export const OUTPUT_FILE = join(ROOT, "packages/api/src/workflowTemplates.generated.ts");
function walk(dir) {
    return readdirSync(dir)
        .filter((name) => !name.startsWith("."))
        .sort()
        .flatMap((name) => {
        const full = join(dir, name);
        return statSync(full).isDirectory() ? walk(full) : [full];
    });
}
export function collectSources(sourceDir = SOURCE_DIR) {
    const out = {};
    for (const file of walk(sourceDir)) {
        const path = relative(sourceDir, file).split("\\").join("/");
        const isWorkflow = !path.includes("/") && path.endsWith(".yml");
        if (isWorkflow || path.startsWith("skills/"))
            out[path] = readFileSync(file, "utf8");
    }
    return out;
}
export function generate(sourceDir = SOURCE_DIR) {
    const sources = collectSources(sourceDir);
    const body = Object.entries(sources)
        .map(([path, content]) => `  ${JSON.stringify(path)}: ${JSON.stringify(content)},`)
        .join("\n");
    return [
        "// Generated by scripts/generate-workflow-templates.ts from github-actions/. Do not edit.",
        "// Run `bun run generate:workflows` after changing anything in github-actions/.",
        "export const WORKFLOW_SOURCES: Readonly<Record<string, string>> = {",
        body,
        "};",
        "",
    ].join("\n");
}
if (import.meta.main) {
    writeFileSync(OUTPUT_FILE, generate());
    console.log(`wrote ${relative(ROOT, OUTPUT_FILE)}`);
}
